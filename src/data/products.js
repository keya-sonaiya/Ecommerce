/**
 * Helper to get a product by ID
 * @param {string} id
 * @returns {object|undefined}
 */
export function getProductById(id) {
  if (!id) return undefined;
  return products.find((p) => p.id.toLowerCase() === id.trim().toLowerCase());
}

/**
 * Helper to get products by category name
 * @param {string} categoryName
 * @returns {Array}
 */
export function getProductsByCategory(categoryName) {
  if (!categoryName || categoryName.toLowerCase() === 'all') return products;
  return products.filter(
    (p) => p.category.toLowerCase() === categoryName.trim().toLowerCase()
  );
}

/**
 * Helper to get products by tag
 * @param {string} tag
 * @returns {Array}
 */
export function getProductsByTag(tag) {
  if (!tag) return [];
  return products.filter(
    (p) => Array.isArray(p.tags) && p.tags.includes(tag.toLowerCase())
  );
}

